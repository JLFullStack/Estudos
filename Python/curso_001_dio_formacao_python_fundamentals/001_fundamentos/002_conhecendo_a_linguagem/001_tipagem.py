# O que são tipos de dados em Python?
# Tipos de dados são categorias que definem o tipo de valor que uma variável pode armazenar.
# Em Python, os tipos de dados mais comuns incluem:
# - int: números inteiros (ex: 1, 2, 3)
# - float: números de ponto flutuante (ex: 1.5, 2.0, 3.14)
# - str: strings ou cadeias de caracteres (ex: "Olá", "Python")
# - bool: valores booleanos (True ou False)

# Exemplos de tipos de dados em Python:
print(1 + 10) # int 
print(1.5 + 1 + 0.5) # float
print(True) # bool
print(False) # bool
print("Python") # str

