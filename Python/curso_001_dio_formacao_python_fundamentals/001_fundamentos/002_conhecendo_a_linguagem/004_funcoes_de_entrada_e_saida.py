# o que são funções de entrada e saída?
# funções de entrada e saída são utilizadas para interagir com o usuário
# funções de entrada permitem que o usuário forneça dados para o programa
# funções de saída permitem que o programa exiba informações para o usuário

# exemplo de funções de entrada: input()
# exemplo de funções de saída: print()

nome = input('\nInforme o seu nome: ')
idade = input('Informe a sua idade: ')


print(f'\nNome informado: {nome}')
print(f'idade informada: {idade}\n')