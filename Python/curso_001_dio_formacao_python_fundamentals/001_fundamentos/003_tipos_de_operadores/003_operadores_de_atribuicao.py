"""
O que são operadores de atribuição?
Operadores de atribuição são usados para atribuir valores a variáveis.
O operador de atribuição mais comum é o sinal de igual (=).
"""
# Exemplo básico de atribuição
x = 10  # Atribui o valor 10 à variável x
y = 5   # Atribui o valor 5 à variável y
print("\nValor inicial de x:", x)
print("Valor inicial de y:", y)

# Operadores de atribuição compostos
x += 5  # Equivalente a "x = x + 5"
print("Após x += 5, x =", x)

x -= 3  # Equivalente a "x = x - 3"
print("Após x -= 3, x =", x)

y *= 2  # Equivalente a "y = y * 2"
print("Após y *= 2, y =", y)

y /= 4  # Equivalente a "y = y / 4"
print("Após y /= 4, y =", y)

x //= 4  # Equivalente a "x = x // 4"
print("Após x //= 4, x =", x)

x **= 2  # Equivalente a "x = x ** 2"
print("Após x **= 2, x =", x)

y %= 3  # Equivalente a "y = y % 3"
print("Após y %= 3, y =", y)

