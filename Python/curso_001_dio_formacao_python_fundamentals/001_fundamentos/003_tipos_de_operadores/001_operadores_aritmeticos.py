# O que são operadores aritméticos?
# Operadores aritméticos são símbolos usados para realizar operações matemáticas básicas.
# Eles incluem adição, subtração, multiplicação, divisão, entre outros.

# Exemplos de operadores aritméticos em Python:
print(f"1 + 1 = {1 + 1}")     # adição
print(f"10 - 2 = {10 - 2}")   # subtração
print(f"4 * 3 = {4 * 3}")     # multiplicação
print(f"12 / 3 = {12 / 3}")   # divisão
print(f"12 // 2 = {12 // 2}") # divisão inteira
print(f"2 ** 3 = {2 ** 3}")   # potência
print(f"10 % 3 = {10 % 3}")   # módulo (resto da divisão)

# Ordem de precedência dos operadores aritméticos:
print("\nordem de precedência:")
print(f"2 + 3 * 4 = {2 + 3 * 4}")       # multiplicação e divisão antes da adição e subtração
print(f"10 * 2 ** 2 = {10 * 2 ** 2}")   # potência antes das outras operações aritméticas
print(f"(2 + 3) * 4 = {(2 + 3) * 4}")   # parênteses alteram a ordem de precedência
print(f"10 - 2 + 5 = {10 - 2 + 5}")     # operações da esquerda para a direita quando têm a mesma precedência
print(f"10 / 2 * 3 = {10 / 2 * 3}\n")     # operações da esquerda para a direita quando têm a mesma precedência
